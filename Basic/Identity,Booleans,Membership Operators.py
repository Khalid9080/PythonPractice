
#--------------IDENTITY OPERATORS------------
# ১. is (একই জিনিস কি না?)
# দুটি ভেরিয়েবল কম্পিউটারের মেমোরিতে হুবহু একই জায়গায় যুক্ত আছে কি না, তা যাচাই করে।
# যদি একই জায়গায় যুক্ত থাকে, তবে উত্তর দেয় True (সত্য)।
# যদি আলাদা জায়গায় থাকে, তবে উত্তর দেয় False (মিথ্যা)।

# ২. is not (আলাদা জিনিস কি না?)
# এটি ঠিক is-এর উল্টো। দুটি ভেরিয়েবল মেমোরির আলাদা জায়গায় আছে কি না, তা যাচাই করে।
# যদি আলাদা জায়গায় থাকে, তবে উত্তর দেয় True (সত্য)।
# যদি একই জায়গায় থাকে, তবে উত্তর দেয় False (মিথ্যা)।

game1=["Football","Cricket","Batminton","Rakbi"]
game2=["GTA6","FC26","RDR2","CODMW4"]
game3=game1

print(game1 is game2) #False
print(game2 is not game3)
print(game3 is game1)


#--------------MEMBERSHIP OPERATORS---------------

# ১. in (ভেতরে আছে কি না?)
# কোনো লিস্ট বা লেখার (String) ভেতরে আপনার খোঁজা জিনিসটি আছে কি না, তা যাচাই করে।
# যদি ভেতরে পাওয়া যায়, তবে উত্তর দেয় True (সত্য)।
# যদি না পাওয়া যায়, তবে উত্তর দেয় False (মিথ্যা)।

# ২. not in (ভেতরে নেই কি না?)
# এটি ঠিক in-এর উল্টো। কোনো কিছুর ভেতরে নির্দিষ্ট উপাদানটি নেই—এই কথাটি সত্য কি না তা যাচাই করে।
# যদি সত্যিই ভেতরে না থাকে, তবে উত্তর দেয় True (সত্য)।
# আর যদি ভেতরে থাকে, তবে উত্তর দেয় False (মিথ্যা)।

fruits=["Apple","Banana","Orange","Mango"]

print("Apple" in fruits)
print("Banana" in fruits)
print("Lemon" in fruits) #False
print("Watermelon" in fruits) #False


#-----------------BOOLEAN TRUE FALSE-----------------
# মূল সূত্র: "কিছু আছে" নাকি "একদম খালি"?
# Python-এ bool() ফাংশনকে একটি স্ক্যানার মেশিনের মতো ভাবতে পারেন। আপনি এই মেশিনের ভেতরে যা-ই দেবেন, সেটি স্ক্যান করে শুধু দুটি কথাই বলবে—ভেতরে কিছু আছে (True), নাকি পুরোপুরি ফাঁকা (False)।
# Truthy (ভেতরে কিছু আছে = True): বক্সে যদি সামান্য কিছুও থাকে (যেমন: ১ টাকা, একটি অক্ষর, বা একটি নাম), তবে Python বলবে True।
# Falsy (পুরোপুরি খালি বা শূন্য = False): বক্সটি যদি একদম ফাঁকা থাকে অথবা মান শূন্য (0) হয়, তবে Python বলবে False।

# ১. কী থাকলে False দেবে? (মাত্র এই ৭টি জিনিস)
# Python-এ শুধু "শূন্য" বা "পুরোপুরি খালি" বোঝায় এমন জিনিসগুলোই False দেয়:
# False (নিজেই মিথ্যা)
# None (কিছুই নেই)
# 0 (সংখ্যা শূন্য—0, 0.0)
# "" (একদম খালি স্ট্রিং, ভেতরে স্পেসও নেই)
# [] (খালি লিস্ট)
# () (খালি টাপল)
# {} (খালি ডিকশনারি বা সেট)

# ২. কী থাকলে True দেবে?
# উপরের ওই ৭টি জিনিস বাদে দুনিয়ার আর যা-ই দেবেন, সবই True দেবে। যেমন:
# 0 ছাড়া যেকোনো সংখ্যা (1, 100, -5, 0.5)
# ভেতরে অন্তত ১টি অক্ষর বা স্পেস আছে এমন স্ট্রিং ("A", " ", "0")
# ভেতরে অন্তত ১টি আইটেম আছে এমন লিস্ট, টাপল বা ডিকশনারি ([0], ["Hi"])
# এক লাইনে মনে রাখার ট্রিক: খালি বা শূন্য হলে False, ভেতরে সামান্য কিছুও থাকলে True।

print(10 > 5)         # আউটপুট: True
print(bool("Dhaka"))  # আউটপুট: True
print(bool(0))        # আউটপুট: False
print(bool(""))       # আউটপুট: False